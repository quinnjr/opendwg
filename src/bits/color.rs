    #[test]
    fn enc_rgb_book_and_transparency() {
        let v = Version::R2018;
        // 0x8000: BS 00 + 0x8000 LE, then BL rgb
        let s = format!(
            "00 {} 00 {}",
            byte_bits(&0x8000u16.to_le_bytes()),
            byte_bits(&0x0011_2233u32.to_le_bytes())
        );
        assert_eq!(
            BitReader::new(&bits(&s)).read_enc(v).unwrap(),
            (
                Color::Rgb {
                    r: 0x11,
                    g: 0x22,
                    b: 0x33
                },
                None,
                false
            )
        );
        // 0xC02A, as AutoCAD writes a book color: no RGB long follows, the low
        // bits are an ACI color (from an R2018 sample's CIRCLE 0x99F).
        let s = format!("00 {} 01", byte_bits(&0xC02Au16.to_le_bytes()));
        let d = bits(&s);
        let mut r = BitReader::new(&d);
        assert_eq!(r.read_enc(v).unwrap(), (Color::Index(0x2A), None, true));
        assert_eq!(r.read_bd().unwrap(), 1.0);
        // 0x2000 | 256: ByLayer with transparency 0x02000040
        let s = format!(
            "00 {} 00 {}",
            byte_bits(&0x2100u16.to_le_bytes()),
            byte_bits(&0x0200_0040u32.to_le_bytes())
        );
        assert_eq!(
            BitReader::new(&bits(&s)).read_enc(v).unwrap(),
            (Color::ByLayer, Some(0x0200_0040), false)
        );
    }

