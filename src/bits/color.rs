/// The ACI index (1-255) nearest to a true color: the smallest squared RGB
/// distance in [`ACI_RGB`], the lowest index on a tie. AutoCAD stores an
/// index beside a true color for readers without true color, chosen by a
/// rule of its own: this metric agrees with it on 3 of the 6 corpus colors
/// (no common metric agrees on all; see `tests/entities.rs`). It is used
/// only for colors set or edited after reading. ACadSharp's `ApproxIndex`
/// is not used.
pub fn nearest_aci(r: u8, g: u8, b: u8) -> u8 {
    let dist = |c: &[u8; 3]| {
        [(r, c[0]), (g, c[1]), (b, c[2])]
            .iter()
            .map(|&(x, y)| (i32::from(x) - i32::from(y)).pow(2))
            .sum::<i32>()
    };
    let mut best = (i32::MAX, 1u8);
    for (i, c) in ACI_RGB.iter().enumerate().skip(1) {
        let d = dist(c);
        if d < best.0 {
            best = (d, i as u8);
        }
    }
    best.1
}

fn from_aci(index: i16) -> Result<Color> {
    from_aci_signed(index).map(|(c, _)| c)
}

fn rgb_color(rgb: u32) -> Color {
    Color::Rgb {
        r: (rgb >> 16) as u8,
        g: (rgb >> 8) as u8,
        b: rgb as u8,
    }
}

impl BitReader<'_> {
    fn read_color_text(&mut self, version: Version) -> Result<String> {
        if version >= Version::R2007 {
            self.read_tu()
        } else {
            // Not decoded with the drawing's code page: each byte is taken
            // as its Latin-1 character, and the writer stores each character
            // back as that byte (`write_color_text`), so any name round-trips.
            // Names here are ASCII in practice.
            let raw = self.read_tv_raw()?;
            Ok(raw.iter().map(|&b| char::from(b)).collect())
        }
    }

    /// CMC. Before R2004 this is a BS ACI index; R2004+ is BS (0), BL RGB with
    /// a color-method top byte, and RC flags (1 = color name, 2 = book name).
    ///
    /// The names are read inline. Inside an R2007+ object they live in the
    /// string stream instead; use `object::ObjReader::read_cmc` there.
    pub fn read_cmc(&mut self, version: Version) -> Result<Color> {
        self.read_cmc_layer(version).map(|(c, _)| c)
    }

    /// CMC as stored on a LAYER: also returns whether the layer is off. Before
    /// R2004 "off" is a negative ACI index (the color keeps its magnitude);
    /// R2004+ CMC carries no such sign, so the flag is always false there.
    pub fn read_cmc_layer(&mut self, version: Version) -> Result<(Color, bool)> {
        if version < Version::R2004 {
            // 257 is "no color" (ObjectARX's ACI value for none), which an
            // R2000 CMC has no other way to store: the R2000 MULTILEADER of
            // `cc-04` (extended corpus) has it as its text's background
            // color, with the fill off, and reads to the end of its data
            // with it.
            return match self.read_bs()? {
                257 => Ok((Color::None, false)),
                i => from_aci_signed(i),
            };
        }
        self.read_cmc_2004(version).map(|c| (c, false))
    }

    fn read_cmc_2004(&mut self, version: Version) -> Result<Color> {
        let (rgb, flags) = self.read_cmc_head()?;
        let color_name = if flags & 1 != 0 {
            self.read_color_text(version)?
        } else {
            String::new()
        };
        let book_name = if flags & 2 != 0 {
            self.read_color_text(version)?
        } else {
            String::new()
        };
        cmc_from_parts(rgb, flags, color_name, book_name)
    }

    /// The R2004+ CMC fields before the names: BS (always 0), the BL RGB long
    /// with its color-method byte, and the RC name flags (1 = color name,
    /// 2 = book name). Callers that keep names elsewhere (the R2007+ string
    /// stream of an object) read the names themselves and finish with
    /// [`cmc_from_parts`].
    pub(crate) fn read_cmc_head(&mut self) -> Result<(u32, u8)> {
        let _index = self.read_bs()?;
        let rgb = self.read_bl()? as u32;
        let flags = self.read_rc()?;
        Ok((rgb, flags))
    }
}

/// Build an R2004+ CMC color from [`BitReader::read_cmc_head`] output and the
/// names (empty when their flag is clear).
pub(crate) fn cmc_from_parts(
    rgb: u32,
    flags: u8,
    color_name: String,
    book_name: String,
) -> Result<Color> {
    if flags & 3 != 0 {
        return Ok(Color::Book {
            rgb: rgb & 0x00FF_FFFF,
            color_name,
            book_name,
        });
    }
    match (rgb >> 24) as u8 {
        METHOD_BY_LAYER => Ok(Color::ByLayer),
        METHOD_BY_BLOCK => Ok(Color::ByBlock),
        METHOD_RGB => Ok(rgb_color(rgb)),
        METHOD_ACI => from_aci((rgb & 0xFF) as i16),
        METHOD_NONE if rgb & 0x00FF_FFFF == 0 => Ok(Color::None),
        m => Err(Error::Corrupt(format!(
            "unknown CMC color method 0x{m:02X}"
        ))),
    }
}

impl BitReader<'_> {
    /// ENC. Returns the color, the raw transparency long if present, and
    /// whether a color-book handle follows in the handle stream.
    ///
    /// ODS says the 0x8000 RGB value is a BS; ACadSharp (MIT,
    /// DwgStreamReaderAC18.ReadEnColor) reads a BL, as does CMC, so BL is used.
    /// When 0x4000 (book color) is set no RGB value follows, even though
    /// AutoCAD also sets 0x8000 (ODS 2.11 implies one does): the low bits hold
    /// an ACI color and the book color itself is the DBCOLOR object. This
    /// follows ACadSharp and was checked against an AutoCAD R2018 sample.
    pub fn read_enc(&mut self, version: Version) -> Result<(Color, Option<u32>, bool)> {
        self.read_enc_with_aci(version)
            .map(|(color, transparency, book, _)| (color, transparency, book))
    }

    /// [`Self::read_enc`], also returning the ACI index AutoCAD stores in the
    /// flag word beside a true color (its nearest index, for readers without
    /// true color); 0 for other colors.
    pub fn read_enc_with_aci(
        &mut self,
        version: Version,
    ) -> Result<(Color, Option<u32>, bool, u16)> {
        if version < Version::R2004 {
            return Ok((from_aci(self.read_bs()?)?, None, false, 0));
        }
        let word = self.read_bs()? as u16;
        let has_book = word & 0x4000 != 0;
        let (color, rgb_aci) = if word & 0x8000 != 0 && !has_book {
            (rgb_color(self.read_bl()? as u32), word & 0x01FF)
        } else {
            (from_aci((word & 0x01FF) as i16)?, 0)
        };
        let transparency = if word & 0x2000 != 0 {
            Some(self.read_bl()? as u32)
        } else {
            None
        };
        Ok((color, transparency, has_book, rgb_aci))
    }
}

