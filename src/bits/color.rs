    /// A pre-R2004 CMC with index 257 is no color: the R2000 MULTILEADER
    /// `cc-04` of the extended corpus stores it as its text's background
    /// color (no fill), and decodes to the end of its data with it. Other
    /// indexes beyond 256 stay errors, and no other color field takes 257.
    #[test]
    fn r2000_cmc_257_is_no_color() {
        use crate::bits::BitWriter;
        let read = |i: i16| {
            let mut w = BitWriter::new();
            w.write_bs(i);
            let bytes = w.into_bytes();
            BitReader::new(&bytes).read_cmc_layer(Version::R2000)
        };
        assert_eq!(read(257).unwrap(), (Color::None, false));
        assert!(read(258).is_err());
        assert!(read(-257).is_err());
        assert_eq!(read(256).unwrap(), (Color::ByLayer, false));
        assert!(from_aci(257).is_err());
    }

    /// Every palette entry follows the palette's structure: 9 fixed colors;
    /// for 10-249, 24 hues 15 degrees apart with 10 shades each (even: the
    /// full hue, odd: halfway to white; scaled by 1, 0.65, 0.5, 0.3, 0.15
    /// and floored); a gray ramp 51-255 for 250-255. The only repeated
    /// colors are the fixed ones repeated in the hue table and white.
    #[test]
    fn aci_palette_structure() {
        let fixed = [
            [255, 0, 0],
            [255, 255, 0],
            [0, 255, 0],
            [0, 255, 255],
            [0, 0, 255],
            [255, 0, 255],
            [255, 255, 255],
            [128, 128, 128],
            [192, 192, 192],
        ];
        assert_eq!(ACI_RGB[1..10], fixed);
        for (i, entry) in ACI_RGB.iter().enumerate().take(250).skip(10) {
            let (hue, shade) = ((i - 10) / 10, (i - 10) % 10);
            let h = hue as f64 * 15.0;
            let comp = |n: f64| {
                let x = (n + h / 60.0) % 6.0;
                255.0 * (1.0 - x.min(4.0 - x).clamp(0.0, 1.0))
            };
            let mut c = [comp(5.0), comp(3.0), comp(1.0)];
            if shade % 2 == 1 {
                c = c.map(|x| (x + 255.0) / 2.0);
            }
            let f = [1.0, 0.65, 0.5, 0.3, 0.15][shade / 2];
            let want = c.map(|x| (x * f + 1e-9).floor() as u8);
            assert_eq!(*entry, want, "ACI {i}");
        }
        let grays: Vec<u8> = ACI_RGB[250..].iter().map(|c| c[0]).collect();
        assert_eq!(grays, [51, 91, 132, 173, 214, 255]);
        assert!(ACI_RGB[250..].iter().all(|c| c[0] == c[1] && c[1] == c[2]));
        let mut first = std::collections::HashMap::new();
        let mut repeats = vec![];
        for (i, c) in ACI_RGB.iter().enumerate().skip(1) {
            if let Some(&j) = first.get(c) {
                repeats.push((j, i));
            } else {
                first.insert(*c, i);
            }
        }
        assert_eq!(
            repeats,
            [
                (1, 10),
                (2, 50),
                (3, 90),
                (4, 130),
                (5, 170),
                (6, 210),
                (7, 255)
            ]
        );
        // Entries ezdxf's table has wrong, and a dark gray that maps to the
        // ramp only with the right one.
        assert_eq!(ACI_RGB[109], [19, 38, 23]);
        assert_eq!(ACI_RGB[145], [63, 111, 127]);
        assert_eq!(ACI_RGB[192], [82, 0, 165]);
        assert_eq!(nearest_aci(60, 60, 60), 250);
    }

