    #[test]
    fn cmc_none_method() {
        let d = cmc_bits("10", 0xC800_0000, 0);
        assert_eq!(
            BitReader::new(&d).read_cmc(Version::R2004).unwrap(),
            Color::None
        );
        let mut w = crate::bits::BitWriter::new();
        w.write_cmc(&Color::None, Version::R2004).unwrap();
        assert_eq!(w.into_bytes(), d);
        // No ENC or pre-R2004 form.
        let mut w = crate::bits::BitWriter::new();
        assert!(w.write_cmc(&Color::None, Version::R2000).is_err());
        assert!(
            w.write_enc(&Color::None, None, false, Version::R2018)
                .is_err()
        );
    }

    #[test]
    fn cmc_unknown_method_is_corrupt() {
        for rgb in [
            0xC400_0000u32,
            0xC800_0001,
            0xC700_0001,
            0xFFFF_FFFF,
            0x0000_0005,
        ] {
            let d = cmc_bits("10", rgb, 0);
            assert!(
                matches!(
                    BitReader::new(&d).read_cmc(Version::R2004),
                    Err(Error::Corrupt(_))
                ),
                "{rgb:#X}"
            );
        }
    }

    #[test]
    fn cmc_layer_off_sign_preserved() {
        let v = Version::R2000;
        let d = bits(&format!("00 {}", byte_bits(&(-5i16).to_le_bytes())));
        assert_eq!(
            BitReader::new(&d).read_cmc_layer(v).unwrap(),
            (Color::Index(5), true)
        );
        assert_eq!(
            BitReader::new(&bits("01 00000101"))
                .read_cmc_layer(v)
                .unwrap(),
            (Color::Index(5), false)
        );
        let d = cmc_bits("10", 0xC000_0000, 0);
        assert_eq!(
            BitReader::new(&d).read_cmc_layer(Version::R2004).unwrap(),
            (Color::ByLayer, false)
        );
    }
