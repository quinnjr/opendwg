use crate::version::Version;

/// A decoded DWG color. More color methods may be added, so the enum is
/// non-exhaustive.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
#[non_exhaustive]
pub enum Color {
    #[default]
    /// The layer's color.
    ByLayer,
    /// The block's color (for entities in a block).
    ByBlock,
    /// AutoCAD Color Index 1..=255.
    Index(u8),
    /// A true color.
    Rgb {
        /// Red.
        r: u8,
        /// Green.
        g: u8,
        /// Blue.
        b: u8,
    },
    /// Color-book color (CMC names present).
    Book {
        /// The color as `0x00RRGGBB`.
        rgb: u32,
        /// The color's name in its book.
        color_name: String,
        /// The color book's name.
        book_name: String,
    },
    /// No color: the R2004+ CMC color method 0xC8 (RGB long exactly
    /// 0xC8000000). It is meaningful where a color may be absent: the corpus
    /// has it as a table style cell's background (no fill), and an R2000
    /// MULTILEADER's text background as the ACI index 257. ODS does not list
    /// the method. It has no ENC (entity color) or pre-R2004 form;
    /// writing it there is an error.
    None,
}

// Color-method byte stored in the top byte of the CMC RGB long. Values checked
// against ACadSharp (MIT), DwgStreamReaderAC18.ReadCmColor: 0xC0000000 is
// ByLayer, a set 0x01000000 bit selects an ACI index in the low byte, anything
// else is true color. ByBlock (0xC1, low byte 0) falls out of the index case.
// Other method bytes (ByPen, Foreground, LayerOff, ...) are rejected rather
// than guessed at, so a write never emits a different color.
pub(super) const METHOD_BY_LAYER: u8 = 0xC0;
pub(super) const METHOD_BY_BLOCK: u8 = 0xC1;
pub(super) const METHOD_RGB: u8 = 0xC2;
pub(super) const METHOD_ACI: u8 = 0xC3;
pub(super) const METHOD_NONE: u8 = 0xC8;

/// Decode an ACI index. A negative index means "layer off" on a LAYER's
/// color; the second element reports that sign.
fn from_aci_signed(index: i16) -> Result<(Color, bool)> {
    let off = index < 0;
    let color = match index.unsigned_abs() {
        0 => Color::ByBlock,
        256 => Color::ByLayer,
        n @ 1..=255 => Color::Index(n as u8),
        n => return Err(Error::Corrupt(format!("invalid ACI color index {n}"))),
    };
    Ok((color, off))
}

