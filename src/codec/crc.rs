/// Table-driven 16-bit CRC with a caller-supplied starting value.
///
/// Feed the previous result as `seed` to accumulate across buffers.
#[must_use]
pub fn crc16(seed: u16, data: &[u8]) -> u16 {
    data.iter().fold(seed, |crc, &b| {
        (crc >> 8) ^ CRC16_TABLE[usize::from(b ^ (crc as u8))]
    })
}

/// Standard reflected CRC-32 (polynomial 0xEDB88320) per ODS 2.14.2.
///
/// The seed is inverted on entry and the result on exit, so `seed = 0`
/// yields the usual CRC-32 and a previous result may be passed as `seed`
/// to continue a calculation. The table is built at compile time from the
/// polynomial, which is the same table ODS prints.
#[must_use]
pub fn crc32(seed: u32, data: &[u8]) -> u32 {
    !data.iter().fold(!seed, |crc, &b| {
        (crc >> 8) ^ CRC32_TABLE[((crc ^ u32::from(b)) & 0xFF) as usize]
    })
}

const CRC32_TABLE: [u32; 256] = {
    let mut table = [0u32; 256];
    let mut i = 0;
    while i < 256 {
        let mut c = i as u32;
        let mut k = 0;
        while k < 8 {
            c = if c & 1 != 0 {
                (c >> 1) ^ 0xEDB8_8320
            } else {
                c >> 1
            };
            k += 1;
        }
        table[i] = c;
        i += 1;
    }
    table
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crc16_empty_returns_seed() {
        assert_eq!(crc16(0xC0C1, b""), 0xC0C1);
    }

    #[test]
    fn crc16_check_value_matches_arc() {
        // The ODS table is the standard CRC-16/ARC table.
        assert_eq!(crc16(0, b"123456789"), 0xBB3D);
    }

    #[test]
    fn crc16_accumulates_across_buffers() {
        let whole = crc16(0xC0C1, b"hello world");
        let split = crc16(crc16(0xC0C1, b"hello "), b"world");
        assert_eq!(whole, split);
    }

    #[test]
    fn crc32_check_value() {
        // ODS seeds with 0 and inverts in/out: the standard CRC-32.
        assert_eq!(crc32(0, b"123456789"), 0xCBF4_3926);
    }

    #[test]
    fn crc32_table_matches_ods_samples() {
        assert_eq!(CRC32_TABLE[1], 0x7707_3096);
        assert_eq!(CRC32_TABLE[2], 0xEE0E_612C);
        assert_eq!(CRC32_TABLE[255], 0x2D02_EF8D);
    }

    #[test]
    fn crc32_accumulates_across_buffers() {
        assert_eq!(crc32(crc32(0, b"1234"), b"56789"), 0xCBF4_3926);
    }
}
